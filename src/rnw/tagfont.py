def text_mask(text: str) -> NDArray[np.bool_]:
    """The ink of ``text`` as a ``HEIGHT`` x columns array, a column of gap between glyphs."""
    unknown = sorted({char for char in text if char not in GLYPHS})
    if unknown or not text:
        message = f"The tag font has no glyph for {unknown!r}" if unknown else "Nothing to draw"
        raise ValueError(message)
    columns = len(text) * (WIDTH + GAP) - GAP
    mask = np.zeros((HEIGHT, columns), dtype=bool)
    for index, char in enumerate(text):
        left = index * (WIDTH + GAP)
        for row, line in enumerate(GLYPHS[char].split("/")):
            for column, cell in enumerate(line):
                mask[row, left + column] = cell == "#"
    return mask
