"""A 5 x 7 bitmap font of capitals and digits, for the tag drawn on a picture.

A font file would make the picture depend on the machine's fonts; a table in the code gives the
same bytes everywhere. Each glyph is seven rows of five cells, ``#`` for ink.
"""

